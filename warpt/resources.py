"""Access to packaged data files.

Reads ``warpt/data/symmetry_basics.json`` through :mod:`importlib.resources` so
the table is found from the installed package regardless of the working
directory. Writes nothing.

The table is generated by the httk data generators and distributed under the
Creative Commons Attribution 4.0 licence; its own metadata (``creator``,
``dcterms:license``, ``prov:wasDerivedFrom``) record the origin.

Public functions: ``load_symmetry_basics``.
"""
import json
from importlib.resources import files

def load_symmetry_basics():
    """Load the packaged space-group / Wyckoff table.

    Returns
    -------
    dict
        The whole JSON-LD document in ``warpt/data/symmetry_basics.json``:
        metadata keys (``@context``, ``version``, ...), ``data`` with
        ``spacegroups`` (a list of 527 space-group setting records, each carrying
        ``it_number``, ``spglib_hall_numbers`` and a ``wyckoff`` list whose entries
        hold the ``orbit`` and ``orbit_mod_centering`` operators) and
        ``pointgroups`` (32 records), and ``indicies`` (spelled this way in the file;
        lookup tables such as ``index_it_number_to_spglib_default_spacegroups``).
        Record selection is described in :func:`warpt.Wyckoff_Projector.load_spacegroup`.

    Raises
    ------
    FileNotFoundError
        If the data file is not packaged.
    json.JSONDecodeError
        If the data file is malformed.
    """
    p = files("warpt").joinpath("data/symmetry_basics.json")
    return json.loads(p.read_text(encoding="utf-8"))
