"""Generate ``docs/REFERENCE.md``, the WARP reference manual, from the ``warpt`` sources.

The sources are read with :mod:`ast` and never imported, so modules that need torch, upet,
mace, ASE, h5py or spglib at import time are documented without those packages being
installed. The only exception is the command-line section: if a module exposes a parser
object or a zero-argument parser factory at module level, that object is built by importing
the module. ``warpt.orchestrator``, ``warpt.MLIP_interface`` and ``warpt.VASP_interface`` build
their parsers inside ``parse_arguments`` / ``main``, so their options are read from the
``add_argument`` calls instead.

Writes ``REFERENCE.md`` next to this script (override with ``-o``). Reads every module of
``warpt`` listed in ``MODULE_ORDER``. The manual has, in this order: the command line of the
three entry points (option, default, help), the environment variables read by the package with
the docstring sentence that documents each, the run directory layout as described by the
workflow and resume module docstrings, and one section per module with its docstring and
every public function and class, each with its signature and docstring.

The same material is also written as one page per module under ``reference/`` (override with
``-r``), together with ``reference/index.md``, for the MkDocs site. Those pages are generated
on every build and are never edited by hand; each carries a first-line HTML comment saying so.
Stale ``.md`` files left in that directory by an earlier run are removed.

Public functions: ``signature``, ``rst_to_md``, ``module_doc``, ``module_summary``,
``public_api``, ``cli_options``, ``environment_variables``, ``run_directory_layout``,
``build``, ``module_page``, ``reference_index``, ``write_reference_pages``, ``main``.
"""
