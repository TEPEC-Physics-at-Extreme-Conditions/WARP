def _tree(name: str) -> ast.Module:
    """Parse ``warpt/<name>.py`` into an AST (the file is never imported)."""
    return ast.parse((PKG / f"{name}.py").read_text(encoding="utf-8"))


def signature(node) -> str:
    """Render the call signature of a function or class node as source text.

    Parameters
    ----------
    node : ast.FunctionDef, ast.AsyncFunctionDef or ast.ClassDef
        Node to describe. A class is rendered from its ``__init__``; a class without one
        (a dataclass) is rendered from its annotated class-level fields, which are the
        parameters of the generated constructor.

    Returns
    -------
    str
        ``name(arg: annotation = default, ...) -> returns``, using the source spelling of
        every annotation and default.
    """
    if isinstance(node, ast.ClassDef):
        init = next((n for n in node.body
                     if isinstance(n, ast.FunctionDef) and n.name == "__init__"), None)
        if init is not None:
            args = _arguments(init, skip_self=True)
        else:
            args = []
            for stmt in node.body:
                if isinstance(stmt, ast.AnnAssign) and isinstance(stmt.target, ast.Name):
                    txt = f"{stmt.target.id}: {ast.unparse(stmt.annotation)}"
                    if stmt.value is not None:
                        txt += f" = {ast.unparse(stmt.value)}"
                    args.append(txt)
        return f"{node.name}({', '.join(args)})"

    out = f"{node.name}({', '.join(_arguments(node))})"
    if node.returns is not None:
        out += f" -> {ast.unparse(node.returns)}"
    return out


def _arguments(node, skip_self: bool = False) -> list[str]:
    """The argument list of a function node, one source-spelled entry per parameter."""
    a = node.args
    out: list[str] = []

    def render(arg, default=None):
        """One parameter with its annotation and default, as written in the source."""
        txt = arg.arg
        if arg.annotation is not None:
            txt += f": {ast.unparse(arg.annotation)}"
        if default is not None:
            txt += f" = {ast.unparse(default)}" if arg.annotation else f"={ast.unparse(default)}"
        return txt

    positional = list(a.posonlyargs) + list(a.args)
    defaults = [None] * (len(positional) - len(a.defaults)) + list(a.defaults)
    for arg, dflt in zip(positional, defaults):
        if skip_self and arg is positional[0] and arg.arg in ("self", "cls"):
            continue
        out.append(render(arg, dflt))
    if a.posonlyargs:
        out.insert(len(a.posonlyargs), "/")
    if a.vararg is not None:
        out.append("*" + render(a.vararg))
    elif a.kwonlyargs:
        out.append("*")
    for arg, dflt in zip(a.kwonlyargs, a.kw_defaults):
        out.append(render(arg, dflt))
    if a.kwarg is not None:
        out.append("**" + render(a.kwarg))
    return out


_ROLE = re.compile(r":[a-z]+:`~?([^`]+)`")

# numpydoc sections whose body is a field list (``name : type`` plus an indented
# description). Their entries become Markdown bullets; every other section stays prose.
FIELD_SECTIONS = {"parameters", "returns", "raises", "yields", "attributes",
                  "other parameters", "warns"}


def _field_list(body: list[str]) -> list[str]:
    """Rewrite the field entries of a numpydoc section body as Markdown bullets.

    An entry is an unindented ``name : type`` (or bare ``type``) line followed by at least
    one indented description line; its description is joined into one bullet. Lines that do
    not form an entry, including prose sections written without indentation, are returned
    unchanged.
    """
    out: list[str] = []
    i = 0
    while i < len(body):
        line = body[i]
        if line.strip() and not line.startswith(" "):
            desc, j = [], i + 1
            while j < len(body) and body[j].startswith(" ") and body[j].strip():
                desc.append(body[j].strip())
                j += 1
            if desc:
                head, text = line.strip(), " ".join(desc)
                if "`" in head:                # already marked up: never nest code spans
                    out.append(f"- {head} — {text}")
                elif " : " in head:
                    name, typ = head.split(" : ", 1)
                    out.append(f"- **{name.strip()}** (`{typ.strip()}`) — {text}")
                else:
                    out.append(f"- `{head}` — {text}")
                i = j
                continue
        out.append(line)
        i += 1
    return out


def rst_to_md(text: str) -> str:
    """Render a reStructuredText docstring as Markdown without changing its wording.

    A cross-reference role (``:func:`~warpt.x.y```) becomes the plain target in a code span;
    a numpydoc section underline (a line of ``-`` or ``=`` under an unindented heading)
    becomes a bold heading followed by a blank line, so that Markdown neither turns the pair
    into a page-level heading nor swallows an indented block behind it; the entries of a
    field-list section (``FIELD_SECTIONS``) become bullets; a trailing reST literal-block
    marker ``::`` becomes a single colon. Indented blocks are otherwise left alone and
    render as code blocks.

    Parameters
    ----------
    text : str
        Docstring as written in the source (already dedented).

    Returns
    -------
    str
        Markdown text.
    """
    text = _ROLE.sub(lambda m: f"`{m.group(1)}`", text)
    lines = text.splitlines()
    out: list[str] = []
    heads: list[tuple[int, str]] = []          # (index in out, heading name)
    i = 0
    while i < len(lines):
        line = lines[i]
        nxt = lines[i + 1] if i + 1 < len(lines) else ""
        underline = nxt.strip() and set(nxt.strip()) <= {"-", "="} and " " not in nxt.strip()
        if line.strip() and not line.startswith(" ") and underline and len(nxt.strip()) >= 3:
            heads.append((len(out), line.strip().lower()))
            out.append(f"**{line.strip()}**")
            if i + 2 < len(lines) and lines[i + 2].strip():
                out.append("")                 # a heading needs a blank line under it
            i += 2
            continue
        if line.rstrip().endswith("::"):
            line = line.rstrip()[:-2] + ":"
        out.append(line.rstrip())
        i += 1

    # Field-list sections run from their heading to the next heading or the end.
    for pos, (idx, name) in enumerate(heads):
        if name not in FIELD_SECTIONS:
            continue
        end = heads[pos + 1][0] if pos + 1 < len(heads) else len(out)
        start = idx + 1
        body = _field_list(out[start:end])
        shift = len(body) - (end - start)
        out[start:end] = body
        heads[pos + 1:] = [(k + shift, n) for k, n in heads[pos + 1:]]
    # An indented block that follows a text line directly would be read as a continuation of
    # that line and lose its layout; a blank line makes it a code block instead. The wrapped
    # line of a bullet is such a continuation on purpose, so a list item and anything
    # indented by less than a code block's four spaces are left joined.
    spaced: list[str] = []
    for line in out:
        indent = len(line) - len(line.lstrip(" "))
        prev = spaced[-1] if spaced else ""
        is_item = bool(re.match(r"\s*([-*+]\s|\d+\.\s)", prev))
        if (line.strip() and indent >= 4 and prev.strip()
                and not prev.startswith(" ") and not is_item):
            spaced.append("")
        spaced.append(line)
    out = spaced

    # Blank lines are trimmed off both ends, but the indentation of the first line is kept:
    # it is what makes an indented block (a table, an equation) render as a code block.
    while out and not out[0].strip():
        out.pop(0)
    while out and not out[-1].strip():
        out.pop()
    return "\n".join(out)


def module_doc(name: str) -> str:
    """Markdown of the module docstring of ``warpt/<name>.py`` (empty string when absent)."""
    doc = ast.get_docstring(_tree(name)) or ""
    return rst_to_md(doc)


def module_summary(name: str) -> str:
    """First sentence of the module docstring of ``warpt/<name>.py``, as one Markdown line.

    Parameters
    ----------
    name : str
        Module name inside the package.

    Returns
    -------
    str
        The summary sentence with newlines folded away, or an empty string when the module
        has no docstring.
    """
    doc = ast.get_docstring(_tree(name)) or ""
    parts = _sentences(doc)
    return rst_to_md(parts[0]).strip() if parts else ""


def public_api(name: str) -> list[tuple[str, str, str]]:
    """Public functions and classes of a module, in source order.

    Parameters
    ----------
    name : str
        Module name inside the package.

    Returns
    -------
    list[tuple[str, str, str]]
        ``(kind, signature, docstring)`` per top-level definition whose name does not start
        with an underscore; ``kind`` is ``"function"`` or ``"class"``. A class carries its
        public methods appended to its docstring.
    """
    out = []
    for node in _tree(name).body:
        if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            continue
        if node.name.startswith("_"):
            continue
        kind = "class" if isinstance(node, ast.ClassDef) else "function"
        doc = rst_to_md(ast.get_docstring(node) or "")
        if kind == "class":
            methods = [m for m in node.body
                       if isinstance(m, ast.FunctionDef) and not m.name.startswith("_")]
            if methods:
                doc += "\n\n**Methods**\n\n" + "\n".join(
                    f"- `{signature(m)}` — {(ast.get_docstring(m) or '').splitlines()[0]}"
                    for m in methods)
        out.append((kind, signature(node), doc))
    return out


def _const(node, names: dict | None = None):
    """Python value of a literal AST node, or its source text when it is not a literal.

    ``names`` may supply the module-level literal constants of the file, which lets an
    expression over them (``sorted(MODELS.keys())``) be evaluated for the manual; only
    ``sorted``, ``list`` and ``tuple`` are available to it, and any failure falls back to the
    source text.
    """
    try:
        return ast.literal_eval(node)
    except Exception:
        pass
    if names:
        try:
            env = {"__builtins__": {"sorted": sorted, "list": list, "tuple": tuple}}
            env.update(names)
            return eval(compile(ast.Expression(node), "<choices>", "eval"), env)  # noqa: S307
        except Exception:
            pass
    return ast.unparse(node)


def _module_constants(tree: ast.Module) -> dict:
    """Module-level names bound to a literal, for resolving expressions in ``add_argument``."""
    out = {}
    for node in tree.body:
        targets = []
        if isinstance(node, ast.Assign):
            targets = [t for t in node.targets if isinstance(t, ast.Name)]
        elif isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
            targets = [node.target]
        if not targets or node.value is None:
            continue
        try:
            value = ast.literal_eval(node.value)
        except Exception:
            continue
        for t in targets:
            out[t.id] = value
    return out


def _parser_factory(name: str):
    """Module-level parser object or zero-argument parser factory of a module, else None.

    Detected from the AST; only when one exists is the module imported to build the parser.
    """
    tree = _tree(name)
    for node in tree.body:
        if isinstance(node, ast.Assign) and isinstance(node.value, ast.Call):
            if ast.unparse(node.value.func).endswith("ArgumentParser"):
                return ast.unparse(node.targets[0])
        if isinstance(node, ast.FunctionDef) and node.name in ("build_parser", "get_parser"):
            if not node.args.args:
                return node.name + "()"
    return None


def cli_options(name: str) -> list[dict]:
    """The argparse options of an entry-point module.

    Uses the parser object when the module exposes one at module level (imported then), and
    otherwise reads every ``add_argument`` call in the source with :mod:`ast`, which is the
    path taken for ``orchestrator``, ``MLIP_interface`` and ``VASP_interface``: all three
    build their parser inside a function.

    Parameters
    ----------
    name : str
        Module name inside the package.

    Returns
    -------
    list[dict]
        One dict per option with ``flags`` (list[str]), ``default``, ``help``, ``choices``,
        ``required`` and ``action``, in declaration order. Options whose help is
        ``argparse.SUPPRESS`` are kept and marked as suppressed.
    """
    factory = _parser_factory(name)
    if factory is not None:                     # pragma: no cover - no module exposes one
        import importlib
        mod = importlib.import_module(f"warpt.{name}")
        parser = eval(factory, vars(mod))       # noqa: S307 - package source, AST-checked
        opts = []
        for act in parser._actions:
            opts.append(dict(flags=list(act.option_strings) or [act.dest],
                             default=act.default, help=act.help,
                             choices=list(act.choices) if act.choices else None,
                             required=bool(act.required),
                             action=type(act).__name__))
        return opts

    tree = _tree(name)
    consts = _module_constants(tree)
    opts = []
    for node in ast.walk(tree):
        if not (isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute)):
            continue
        if node.func.attr != "add_argument":
            continue
        flags = [_const(a) for a in node.args]
        kw = {k.arg: k.value for k in node.keywords if k.arg}
        help_txt = None
        if "help" in kw:
            help_txt = (argparse.SUPPRESS
                        if ast.unparse(kw["help"]).endswith("SUPPRESS") else _const(kw["help"]))
        if not flags:
            flags = [_const(kw["dest"])] if "dest" in kw else ["(positional)"]
        choices = _const(kw["choices"], consts) if "choices" in kw else None
        if isinstance(choices, (set, frozenset)):
            choices = sorted(choices)
        opts.append(dict(
            flags=flags,
            default=_const(kw["default"]) if "default" in kw else None,
            help=help_txt,
            choices=choices,
            required=bool(_const(kw["required"])) if "required" in kw else False,
            action=_const(kw["action"]) if "action" in kw else "store",
        ))
    return opts


_FIELD = re.compile(r"^\S[^:]*? : .+$")


def _sentences(text: str) -> list[str]:
    """Split docstring text into sentences, keeping numpydoc scaffolding out of them.

    A blank line, a section underline and a numpydoc ``name : type`` field header each end
    the current block; inside a block newlines are folded to spaces and the text is split
    after a full stop. Semicolons do not split, so a clause such as ``...; None when neither
    is set`` stays with its sentence.
    """
    blocks: list[list[str]] = [[]]
    for line in text.splitlines():
        s = line.strip()
        is_rule = bool(s) and set(s) <= {"-", "="} and " " not in s
        if not s or is_rule or _FIELD.match(line):
            blocks.append([])
            continue
        blocks[-1].append(s)
    out = []
    for block in blocks:
        if not block:
            continue
        flat = " ".join(" ".join(block).split())
        for part in re.split(r"(?<=\.)\s+(?=[A-Z`(“\"]|``)", flat):
            if part.strip():
                out.append(part.strip())
    return out


def _all_docstrings() -> list[tuple[str, str]]:
    """Every docstring in the package as ``(where, text)``, modules in ``MODULE_ORDER``."""
    out = []
    for name in MODULE_ORDER:
        tree = _tree(name)
        doc = ast.get_docstring(tree)
        if doc:
            out.append((f"warpt.{name}", doc))
        for node in ast.walk(tree):
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
                d = ast.get_docstring(node)
                if d:
                    out.append((f"warpt.{name}.{node.name}", d))
    return out


def environment_variables() -> list[dict]:
    """Every environment variable the package reads, with the sentence that documents it.

    Reads are ``os.environ.get(...)`` and ``os.environ[...]`` in a load context; a write is
    an assignment to ``os.environ[...]`` or an ``os.environ.pop(...)``.

    Returns
    -------
    list[dict]
        One dict per variable, sorted by name: ``name``, ``modules`` (sorted list),
        ``default`` (the literal passed to ``get``, or None), ``written`` (bool) and ``doc``
        (the docstring sentence that documents the variable, or an empty string). The
        sentence is chosen from the docstrings of the modules that read the variable, and
        from the rest of the package only when none of those mentions it; among the
        candidates, a docstring's own summary sentence comes first, otherwise the shortest
        and therefore most specific one.
    """
    found: dict[str, dict] = {}

    def note(var, module, default=None, written=False):
        """Record one occurrence of ``var`` in ``module``."""
        e = found.setdefault(var, dict(name=var, modules=set(), default=None, written=False))
        e["modules"].add(f"warpt.{module}")
        if default is not None and e["default"] is None:
            e["default"] = default
        e["written"] = e["written"] or written

    for name in MODULE_ORDER:
        for node in ast.walk(_tree(name)):
            if isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute):
                base = ast.unparse(node.func.value)
                if base == "os.environ" and node.func.attr in ("get", "pop") and node.args:
                    var = _const(node.args[0])
                    if isinstance(var, str):
                        dflt = _const(node.args[1]) if len(node.args) > 1 else None
                        note(var, name, default=dflt, written=(node.func.attr == "pop"))
            elif isinstance(node, ast.Subscript) and ast.unparse(node.value) == "os.environ":
                var = _const(node.slice)
                if isinstance(var, str):
                    note(var, name, written=isinstance(node.ctx, ast.Store))

    docs = _all_docstrings()
    out = []
    for var, e in sorted(found.items()):
        own = sorted(e["modules"])
        hits = [(where, s, i) for where, text in docs
                for i, s in enumerate(_sentences(text)) if var in s]
        local = [h for h in hits if any(h[0] == m or h[0].startswith(m + ".") for m in own)]
        pool = local or hits
        sentence = ""
        if pool:
            # A docstring's own summary sentence wins; otherwise the shortest, i.e. the most
            # specific, sentence that names the variable.
            where, s, _i = min(pool, key=lambda h: (h[2] != 0, len(h[1])))
            sentence = f"{rst_to_md(s).strip()} *({where})*"
        out.append(dict(name=var, modules=own, default=e["default"],
                        written=e["written"], doc=sentence))
    return out


def run_directory_layout() -> list[tuple[str, str]]:
    """Paragraphs of the module docstrings that describe the on-disk layout of a run.

    Returns
    -------
    list[tuple[str, list[str]]]
        ``(module, paragraphs)`` for every ``LAYOUT_MODULES`` module, keeping the paragraphs
        of its docstring that name a run directory (``LAYOUT_TOKENS``) and dropping the
        index paragraphs (``LAYOUT_SKIP_PREFIXES``), in manual order.
    """
    out = []
    for name in LAYOUT_MODULES:
        doc = ast.get_docstring(_tree(name)) or ""
        paras = []
        for para in re.split(r"\n\s*\n", doc):
            if para.lstrip().startswith(LAYOUT_SKIP_PREFIXES):
                continue
            if any(tok in para for tok in LAYOUT_TOKENS):
                paras.append(rst_to_md(para))
        if paras:
            out.append((f"warpt.{name}", paras))
    return out


def _fmt_default(opt) -> str:
    """Markdown cell for an option's default, including required flags and store_true."""
    if opt["required"]:
        return "*required*"
    if opt["action"] in ("store_true", "StoreTrueAction", "_StoreTrueAction"):
        return "`False` (flag)"
    d = opt["default"]
    if d is None:
        return "`None`"
    return f"`{d!r}`" if not isinstance(d, str) else f"`{d}`"


def _fmt_help(opt) -> str:
    """Markdown cell for an option's help text, with its choices."""
    txt = opt["help"]
    if txt is argparse.SUPPRESS:
        return "*(hidden from --help)*"
    if not txt:
        txt = "—"
    txt = " ".join(str(txt).split()).replace("|", r"\|")
    if opt["choices"]:
        txt += f" *(choices: {', '.join(str(c) for c in opt['choices'])})*"
    return txt


def build() -> str:
    """Assemble the whole manual as one Markdown document.

    Returns
    -------
    str
        The text written to ``REFERENCE.md``: command line, environment variables, run
        directory layout, then the module reference in ``MODULE_ORDER``.
    """
    L: list[str] = []
    L.append("# WARP reference manual")
    L.append("")
    L.append("WARP — Wyckoff-constrained Anharmonic Relaxation at Pressure and temperature. "
             "Python package `warpt`.")
    L.append("")
    L.append("Generated from the sources by `docs/make_reference.py`; every docstring, "
             "signature, option and default below is read out of `warpt/*.py`. Edit the "
             "code, not this file.")
    L.append("")

    L.append("## Contents")
    L.append("")
    L.append("- [Command line](#command-line)")
    L.append("- [Environment variables](#environment-variables)")
    L.append("- [Run directory layout](#run-directory-layout)")
    L.append("- [Module reference](#module-reference)")
    for name in MODULE_ORDER:
        L.append(f"  - [warpt.{name}](#warpt{name.lower().replace('_', '')})")
    L.append("")

    L.append("## Command line")
    L.append("")
    for name, title in CLI_MODULES:
        L.append(f"### {title}")
        L.append("")
        opts = cli_options(name)
        L.append("| Option | Default | Help |")
        L.append("| --- | --- | --- |")
        for opt in opts:
            flags = ", ".join(f"`{f}`" for f in opt["flags"])
            L.append(f"| {flags} | {_fmt_default(opt)} | {_fmt_help(opt)} |")
        L.append("")
        if any(o["help"] in (None, "") for o in opts):
            L.append("Options with `—` carry no argparse help text; they are described in "
                     f"the docstrings of `warpt.{name}` below.")
            L.append("")

    L.append("## Environment variables")
    L.append("")
    L.append("| Variable | Read by | Default | Documented as |")
    L.append("| --- | --- | --- | --- |")
    for e in environment_variables():
        mods = ", ".join(f"`{m}`" for m in e["modules"])
        dflt = "—" if e["default"] is None else f"`{e['default']}`"
        doc = e["doc"].replace("|", r"\|") or "—"
        name = f"`{e['name']}`" + (" *(also written)*" if e["written"] else "")
        L.append(f"| {name} | {mods} | {dflt} | {doc} |")
    L.append("")

    L.append("## Run directory layout")
    L.append("")
    L.append("Taken from the module docstrings that define it.")
    L.append("")
    for where, paras in run_directory_layout():
        L.append(f"**`{where}`**")
        L.append("")
        for para in paras:
            L.append(para)
            L.append("")

    L.append("## Module reference")
    L.append("")
    for name in MODULE_ORDER:
        L.append(f"### warpt.{name}")
        L.append("")
        doc = module_doc(name)
        if doc:
            L.append(doc)
            L.append("")
        for kind, sig, doc in public_api(name):
            L.append(f"#### {'class ' if kind == 'class' else ''}`{sig}`")
            L.append("")
            if doc:
                L.append(doc)
                L.append("")
    return "\n".join(L).rstrip() + "\n"


def module_page(name: str) -> str:
    """One MkDocs page for a single module: docstring, then every public definition.

    Parameters
    ----------
    name : str
        Module name inside the package.

    Returns
    -------
    str
        Markdown text beginning with ``GENERATED_NOTE``: the module docstring under a
        ``# warpt.<name>`` heading, then a ``## Public API`` section with one
        ``### `signature``` heading per public function and class, or a one-line note when
        the module defines none.
    """
    L = [GENERATED_NOTE, "", f"# warpt.{name}", ""]
    doc = module_doc(name)
    if doc:
        L += [doc, ""]
    api = public_api(name)
    if api:
        L += ["## Public API", ""]
        for kind, sig, body in api:
            L.append(f"### {'class ' if kind == 'class' else ''}`{sig}`")
            L.append("")
            if body:
                L += [body, ""]
    else:
        L += ["This module defines no public function or class; everything above describes "
              "module-level behaviour.", ""]
    return "\n".join(L).rstrip() + "\n"


def all_definitions(name: str) -> list[dict]:
    """Every function, method and class of a module, private and nested ones included.

    Parameters
    ----------
    name : str
        Module name inside the package.

    Returns
    -------
    list[dict]
        One entry per definition, in source order, with the keys ``qualname`` (dotted path
        inside the module, e.g. ``run_jobs_parallel.launch``), ``kind`` (``"function"``,
        ``"method"`` or ``"class"``), ``signature``, ``doc`` (Markdown, empty when the
        definition has no docstring), ``line`` (line number in the source) and ``anchor``
        (the HTML id of its heading on the "All functions" page).
    """
    out = []

    def visit(node, prefix, in_class):
        for child in node.body:
            if isinstance(child, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
                qual = f"{prefix}.{child.name}" if prefix else child.name
                is_class = isinstance(child, ast.ClassDef)
                kind = "class" if is_class else ("method" if in_class else "function")
                out.append({
                    "qualname": qual, "kind": kind, "signature": signature(child),
                    "doc": rst_to_md(ast.get_docstring(child) or ""), "line": child.lineno,
                    "anchor": f"{name}--{qual}".replace(".", "-").replace("_", "-").lower(),
                })
                visit(child, qual, is_class)

    visit(_tree(name), "", False)
    return out


def all_functions_page() -> str:
    """The ``reference/all-functions.md`` page: every definition of the package on one page.

    Returns
    -------
    str
        Markdown text beginning with ``GENERATED_NOTE``: an alphabetical index (name,
        module, kind, first line of the docstring) linking to one section per definition,
        then the definitions module by module in ``MODULE_ORDER`` with their signature,
        source line and full docstring. Private helpers (leading underscore) and functions
        defined inside other functions are included, so the page can be searched for any
        name that appears in the source.
    """
    entries = [(name, d) for name in MODULE_ORDER for d in all_definitions(name)]
    L = [GENERATED_NOTE, "", "# All functions", ""]
    L.append(f"Every function, method and class of the `warpt` package ({len(entries)} "
             "definitions), including private helpers and functions defined inside other "
             "functions, with its signature and documentation as written in the source. Use the "
             "search box or the browser's find-in-page to look up a name; the module pages carry "
             "the same documentation for the public definitions together with the module "
             "description.")
    L.append("")
    L.append("## Index")
    L.append("")
    L.append("| Name | Module | Kind | Summary |")
    L.append("| --- | --- | --- | --- |")
    for name, d in sorted(entries, key=lambda e: (e[1]["qualname"].split(".")[-1].lstrip("_").lower(), e[0])):
        first = (d["doc"].strip().splitlines() or ["—"])[0].replace("|", r"\|")
        L.append(f"| [`{d['qualname']}`](#{d['anchor']}) | `warpt.{name}` | {d['kind']} | {first} |")
    L.append("")
    for name in MODULE_ORDER:
        defs = all_definitions(name)
        L.append(f"## warpt.{name}")
        L.append("")
        if not defs:
            L += ["This module defines no function or class.", ""]
            continue
        for d in defs:
            prefix = "class " if d["kind"] == "class" else ""
            L.append(f"### {prefix}`{d['qualname']}` {{ #{d['anchor']} }}")
            L.append("")
            L.append(f"`{d['signature']}` — `warpt/{name}.py`, line {d['line']}")
            L.append("")
            L.append(d["doc"] if d["doc"] else "*No docstring.*")
            L.append("")
    return "\n".join(L).rstrip() + "\n"


def reference_index() -> str:
    """The ``reference/index.md`` page: one table row per module, in ``MODULE_ORDER``.

    Returns
    -------
    str
        Markdown text beginning with ``GENERATED_NOTE``, with a link and a one-line summary
        for every module of the package.
    """
    L = [GENERATED_NOTE, "", "# Module reference", ""]
    L.append("Every page below is generated from the sources of the `warpt` package by "
             "`docs/make_reference.py`, which reads them with `ast` and never imports them. "
             "The signatures, defaults and descriptions are therefore exactly what the code "
             "says. The entry point comes first, then the pipeline stages in the order a run "
             "executes them, then the support layers and the standalone tools.")
    L.append("")
    L.append("| Module | What it does |")
    L.append("| --- | --- |")
    for name in MODULE_ORDER:
        summary = module_summary(name).replace("|", r"\|") or "—"
        L.append(f"| [`warpt.{name}`]({name}.md) | {summary} |")
    L.append("")
    L.append("To search every function of the package on one page, private helpers included, "
             "see [All functions](all-functions.md).")
    L.append("")
    return "\n".join(L).rstrip() + "\n"


def write_reference_pages(outdir: Path) -> list[Path]:
    """Write ``index.md``, one page per module and ``all-functions.md`` into ``outdir``, removing stale pages.

    Parameters
    ----------
    outdir : pathlib.Path
        Directory to fill; created when absent. Any ``.md`` file in it that this call does
        not write is deleted, so a module dropped from ``MODULE_ORDER`` leaves no orphan
        page behind in the site.

    Returns
    -------
    list[pathlib.Path]
        The files written, ``index.md`` first.
    """
    outdir.mkdir(parents=True, exist_ok=True)
    written = [outdir / "index.md"]
    (outdir / "index.md").write_text(reference_index(), encoding="utf-8")
    for name in MODULE_ORDER:
        path = outdir / f"{name}.md"
        path.write_text(module_page(name), encoding="utf-8")
        written.append(path)
    path = outdir / "all-functions.md"
    path.write_text(all_functions_page(), encoding="utf-8")
    written.append(path)
    keep = {p.name for p in written}
    for stale in sorted(outdir.glob("*.md")):
        if stale.name not in keep:
            stale.unlink()
            print(f"[make_reference] removed stale page {stale}")
    return written


def main() -> int:
    """Command-line entry point: write the manual and the per-module pages, then report.

    Options: ``-o``/``--output`` (default ``REFERENCE.md`` next to this script) and
    ``-r``/``--reference-dir`` (default ``reference/`` next to this script).

    Returns
    -------
    int
        Process exit code, always 0.
    """
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("-o", "--output", default=str(HERE / "REFERENCE.md"),
                   help="file to write (default: REFERENCE.md next to this script)")
    p.add_argument("-r", "--reference-dir", default=str(REFERENCE_DIR),
                   help="directory for the per-module pages of the MkDocs site "
                        "(default: reference/ next to this script)")
    a = p.parse_args()
    text = build()
    out = Path(a.output)
    out.write_text(text, encoding="utf-8")
    print(f"[make_reference] wrote {out} ({out.stat().st_size} bytes, "
          f"{len(text.splitlines())} lines, {len(MODULE_ORDER)} modules)")
    pages = write_reference_pages(Path(a.reference_dir))
    print(f"[make_reference] wrote {len(pages)} pages in {Path(a.reference_dir)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
